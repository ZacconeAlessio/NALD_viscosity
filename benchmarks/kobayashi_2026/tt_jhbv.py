"""Tang-Toennies/JHBV pair potential for the Kobayashi argon benchmark.

This module mirrors the two-body force law in the collaborator-supplied
`repatt_scale_TT_ATM_MD.f90` without redistributing that source.

The TT/JHBV potential is

    U(r)/k_B = A exp(a1 r + a2 r^2 + a_-1/r + a_-2/r^2)
               - sum_{p=6,8,...,16} C_p r^{-p} f_p(b r),

with Tang-Toennies damping

    f_p(x) = 1 - exp(-x) sum_{k=0}^p x^k/k!.

For the Kobayashi attraction-scaled pair model, the repulsive branch is kept
unchanged below the TT minimum and the branch above the minimum is multiplied
by the attraction scale s.  The collaborator's production code also changes
the force cutoff: s=0 uses r_min, whereas every non-zero s uses 5*sigma_MD.

The source-code Boltzmann constant is retained here for exact force-level
reproduction.  This differs negligibly from the modern SI exact value.
"""

from __future__ import annotations

import math

import numpy as np

# Constants copied from the collaborator-supplied production source/manual.
SOURCE_KB = 1.380658e-23  # J/K
NM = 1.0e-9
ARGON_MASS_KG = 6.6335e-26
MD_SIGMA_M = 3.3952e-10
MD_SIGMA_NM = MD_SIGMA_M / NM
RMIN_M = 3.7618e-10
RMIN_NM = RMIN_M / NM
EPS_TT_J = 1.976041929857538e-21
EPSILON_OVER_KB_K = EPS_TT_J / SOURCE_KB
FULL_PAIR_CUTOFF_M = 5.0 * MD_SIGMA_M
ATM_COEFFICIENT_J_M9 = 7.32e-108

# Backward-compatible alias.  In the MD source this sigma is a length parameter
# used for cutoff construction; it is not the TT zero-crossing distance.
SIGMA_NM = MD_SIGMA_NM

# TT/JHBV parameters in K and nm units.  C12-C16 are generated by exactly the
# recurrence used in the supplied Fortran source.
A_K = 4.61330146e7
A1_NM1 = -2.98337630e1
A2_NM2 = -9.71208881
AM1_NM = 2.75206827e-2
AM2_NM2 = -1.01489050e-2
B_NM1 = 4.02517211e1

_C6 = 4.42812017e-1
_C8 = 3.26707684e-2
_C10 = 2.45656537e-3
_C12 = _C6 * (_C10 / _C8) ** 3
_C14 = _C8 * (_C12 / _C10) ** 3
_C16 = _C10 * (_C14 / _C12) ** 3

C_K_NM = {
    6: _C6,
    8: _C8,
    10: _C10,
    12: _C12,
    14: _C14,
    16: _C16,
}


def _scalarize(original, *values):
    if np.asarray(original).ndim == 0:
        return tuple(float(np.asarray(value)) for value in values)
    return values


def _damping(p: int, x):
    """Return f_p(x), df_p/dx and d2f_p/dx2 for scalar or array x."""
    x = np.asarray(x, dtype=float)
    series = np.ones_like(x)
    term = np.ones_like(x)
    for k in range(1, p + 1):
        term = term * x / k
        series = series + term

    ex = np.exp(-x)
    f = 1.0 - ex * series
    fp_x = ex * x**p / math.factorial(p)
    fpp_x = ex * x ** (p - 1) * (p - x) / math.factorial(p)
    return f, fp_x, fpp_x


def base_potential_K(r_nm):
    """Return U/kB [K], d(U/kB)/dr [K/nm], d2(U/kB)/dr2 [K/nm^2].

    `r_nm` may be a scalar or NumPy-compatible array.
    """
    original = r_nm
    r = np.asarray(r_nm, dtype=float)
    if np.any(r <= 0.0):
        raise ValueError("r must be positive")

    phi = A1_NM1 * r + A2_NM2 * r * r + AM1_NM / r + AM2_NM2 / (r * r)
    rep = A_K * np.exp(phi)

    phi1 = A1_NM1 + 2.0 * A2_NM2 * r - AM1_NM / r**2 - 2.0 * AM2_NM2 / r**3
    phi2 = 2.0 * A2_NM2 + 2.0 * AM1_NM / r**3 + 6.0 * AM2_NM2 / r**4
    rep1 = rep * phi1
    rep2 = rep * (phi1 * phi1 + phi2)

    disp = np.zeros_like(r)
    disp1 = np.zeros_like(r)
    disp2 = np.zeros_like(r)
    x = B_NM1 * r

    for p, c in C_K_NM.items():
        f, fx, fxx = _damping(p, x)
        fr = B_NM1 * fx
        frr = B_NM1**2 * fxx

        rp = r ** (-p)
        disp += c * rp * f
        disp1 += c * (-p * r ** (-p - 1) * f + rp * fr)
        disp2 += c * (
            p * (p + 1) * r ** (-p - 2) * f
            - 2.0 * p * r ** (-p - 1) * fr
            + rp * frr
        )

    return _scalarize(original, rep - disp, rep1 - disp1, rep2 - disp2)


def scaled_potential_K(r_nm, attraction_scale: float):
    """Return the attraction-scaled TT potential and first two derivatives.

    This applies the WCA-like branch scaling but does not apply the production
    cutoff.  Below r_min, with scale_rep=1 as used in the benchmark,

        U_s = U + (1-s) epsilon,

    while force and curvature remain those of the full TT potential.  Above
    r_min, U, dU/dr and d2U/dr2 are multiplied by s.
    """
    s = float(attraction_scale)
    if s < 0.0:
        raise ValueError("attraction_scale must be non-negative")

    original = r_nm
    r = np.asarray(r_nm, dtype=float)
    u, u1, u2 = base_potential_K(r)
    below = r < RMIN_NM

    u = np.where(below, u + (1.0 - s) * EPSILON_OVER_KB_K, s * u)
    u1 = np.where(below, u1, s * u1)
    u2 = np.where(below, u2, s * u2)
    return _scalarize(original, u, u1, u2)


def scaled_potential_SI(r_m, attraction_scale: float):
    """Return U [J], dU/dr [N], and d2U/dr2 [N/m], without cutoff."""
    original = r_m
    u, u1, u2 = scaled_potential_K(np.asarray(r_m, dtype=float) / NM, attraction_scale)
    values = (
        SOURCE_KB * np.asarray(u),
        SOURCE_KB * np.asarray(u1) / NM,
        SOURCE_KB * np.asarray(u2) / (NM * NM),
    )
    return _scalarize(original, *values)


def source_pair_cutoff_m(attraction_scale: float) -> float:
    """Return the two-body cutoff used by the supplied production source."""
    s = float(attraction_scale)
    if s < 0.0:
        raise ValueError("attraction_scale must be non-negative")
    return RMIN_M if s == 0.0 else FULL_PAIR_CUTOFF_M


def source_force_curvature_SI(r_m, attraction_scale: float):
    """Return dU/dr [N] and d2U/dr2 [N/m] with the production cutoff applied.

    Outside the appropriate cutoff both quantities are zero.  These are the
    quantities required for force and Hessian construction; additive energy
    shifts in the MD source therefore do not enter.
    """
    original = r_m
    r = np.asarray(r_m, dtype=float)
    _, u1, u2 = scaled_potential_SI(r, attraction_scale)
    inside = r <= source_pair_cutoff_m(attraction_scale)
    u1 = np.where(inside, u1, 0.0)
    u2 = np.where(inside, u2, 0.0)
    return _scalarize(original, u1, u2)
